function createResource(data: {
  id: string;
  title: string;
  summary: string;
  type: Resource["type"];
  topic: string;
  tags: string[];
  keywords: string[];
  sourceUrl: string;
  channelName: string;
  categoryName: string;
  sharedBy: string;
  discordUrl: string;
  channelId: string;
  isOfficial?: boolean;
  sharedAt?: string;
}): Resource {
  return {
    id: data.id,
    title: data.title,
    summary: data.summary,
    type: data.type,
    topic: data.topic,
    tags: data.tags,
    sourceChannel: data.categoryName,
    sourceUrl: data.sourceUrl,
    sharedBy: data.sharedBy,
    sharedAt: data.sharedAt || "2024-01-01T00:00:00Z",
    keywords: data.keywords,
    isOfficial: data.isOfficial || false,
    source: {
      guildId: GUILD_ID,
      channelId: data.channelId,
      channelName: data.channelName,
      messageId: data.id,
      messageUrl: data.discordUrl,
      authorRole: data.isOfficial ? "official" : "community",
      sharedAt: data.sharedAt || "2024-01-01T00:00:00Z",
    },
    contentSnippet: data.summary.slice(0, 500),
    assets: [],
    status: "published",
    canonicalKey: data.title.toLowerCase().replace(/\s+/g, "-").replace(/[^a-z0-9-]/g, ""),
  };
}

